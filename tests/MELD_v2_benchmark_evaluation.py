"""MELD-v2 custom benchmark evaluator for SpeakerRAG (LLM-as-judge).

Given the benchmark file produced by `MELD_based_benchmark_generation_v2.py`
(default: ./new_bench_with_audio_v2.json), this script:

  1. Asks every question to the running SpeakerRAG system:
       POST /rag/retrieve   -> build the FACT SHEET + recommended prompt.
                               For `audio_identity` questions the probe .wav is
                               uploaded so the system has to identify the voice.
       POST /llm/generate   -> the backend's own LLM (Qwen3-14B in `local` mode)
                               answers from the recommended prompt. This is the
                               system's actual answer.
  2. Scores each system answer against the benchmark ground truth with an
     OpenAI model acting as an LLM judge (one unified rubric per answer_format).
  3. Reports accuracy per q_type, per (q_type.subtype), and overall, plus a
     "strict" accuracy (fraction scored exactly 1.0). Per-question verdicts are
     streamed to a JSONL; the aggregate summary is written to a JSON.

PREREQUISITES
  - SpeakerRAG FastAPI server reachable at --base-url.
  - MELD train split already enrolled (done via the UI).
  - Backend extractor mode is 'local' (so /llm/generate is the answerer):
        curl -X POST <base-url>/admin/extractor_mode \\
             -H 'Content-Type: application/json' -d '{"mode":"local"}'
  - export OPENAI_API_KEY=sk-...   (judge only)

USAGE
  python tests/MELD_v2_benchmark_evaluation.py \\
      --benchmark tests/new_bench_with_audio_v2.json \\
      --base-url http://127.0.0.1:8006 \\
      --judge-model gpt-4o \\
      --output tests/meld_v2_results
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import time
from collections import defaultdict
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional

import requests

try:
    from openai import OpenAI
except ImportError:
    sys.exit("Missing dependency: pip install openai")


# ---------------------------------------------------------------------------
# SpeakerRAG client helpers
# ---------------------------------------------------------------------------
def assert_backend_local(base_url: str) -> None:
    """The system answer is generated by /llm/generate, which only works when
    the backend extractor mode is 'local'. Fail fast with a clear message."""
    r = requests.get(f"{base_url}/admin/extractor_mode", timeout=10)
    r.raise_for_status()
    data = r.json()
    if str(data.get("mode", "")).lower() != "local" or not data.get("enabled", False):
        raise RuntimeError(
            f"backend extractor mode is {data.get('mode')!r} (enabled={data.get('enabled')}). "
            f"POST {{\"mode\":\"local\"}} to {base_url}/admin/extractor_mode and wait for it "
            f"to return before running this benchmark."
        )


_AUDIO_INDEX_CACHE: Dict[str, Dict[str, str]] = {}


def _index_audio_root(audio_root: str) -> Dict[str, str]:
    """Map {basename: absolute_path} for every *.wav under audio_root (cached)."""
    if audio_root not in _AUDIO_INDEX_CACHE:
        root = Path(audio_root)
        if not root.is_dir():
            raise FileNotFoundError(f"--audio-root not found: {audio_root}")
        _AUDIO_INDEX_CACHE[audio_root] = {p.name: str(p.resolve()) for p in root.rglob("*.wav")}
    return _AUDIO_INDEX_CACHE[audio_root]


def resolve_audio_path(item: Dict[str, Any], audio_root: Optional[str]) -> Optional[str]:
    """Resolve an audio_identity clip to a path readable by this process.

    The benchmark stores host paths in `audio_path`. When --audio-root is given
    (e.g. the container's /app/MELD.Raw), we relocate the clip by its basename
    (`audio_file`), falling back to a recursive search — robust to folder drift.
    Without --audio-root we use the raw `audio_path` as-is.
    """
    raw = item.get("audio_path")
    if not raw:
        return None
    if not audio_root:
        return raw

    basename = item.get("audio_file") or os.path.basename(raw)
    # Fast paths first: the common MELD layout, then a flat root.
    for cand in (os.path.join(audio_root, "dev_splits_complete", basename),
                 os.path.join(audio_root, basename)):
        if os.path.isfile(cand):
            return cand
    # Fallback: recursive basename lookup.
    found = _index_audio_root(audio_root).get(basename)
    if not found:
        raise FileNotFoundError(
            f"clip {basename!r} (benchmark path {raw!r}) not found under {audio_root}"
        )
    return found


def retrieve_prompt(base_url: str, question: str, audio_path: Optional[str]) -> str:
    """Build the FACT SHEET and return the recommended prompt.

    For audio_identity questions we upload the probe .wav so the full
    identification pipeline runs; otherwise it is a text-only query.
    """
    url = f"{base_url}/rag/retrieve"
    data = {"question": question}
    if audio_path:
        if not os.path.isfile(audio_path):
            raise FileNotFoundError(f"audio clip not found: {audio_path}")
        with open(audio_path, "rb") as fh:
            files = [("audios", (os.path.basename(audio_path), fh, "audio/wav"))]
            r = requests.post(url, data=data, files=files, timeout=600)
    else:
        r = requests.post(url, data=data, timeout=300)
    if r.status_code != 200:
        raise RuntimeError(f"/rag/retrieve {r.status_code}: {r.text[:300]}")
    body = r.json()
    prompt = body.get("recommended_prompt") or ""
    if not prompt:
        raise RuntimeError("backend returned an empty recommended_prompt")
    return prompt


def llm_generate(base_url: str, prompt: str, max_new_tokens: int) -> str:
    """Run the recommended prompt through the backend's own LLM (Qwen3-14B)."""
    r = requests.post(
        f"{base_url}/llm/generate",
        json={"prompt": prompt, "max_new_tokens": int(max_new_tokens)},
        timeout=600,
    )
    if r.status_code != 200:
        raise RuntimeError(f"/llm/generate {r.status_code}: {r.text[:300]}")
    return (r.json().get("text") or "").strip()


# ---------------------------------------------------------------------------
# LLM judge
# ---------------------------------------------------------------------------
_JUDGE_SYS = """You are a strict, fair evaluator for a speaker-aware audio RAG benchmark.
You are given one benchmark question, its reference ground truth, and the answer produced
by the system under test. Decide how well the system answer matches the ground truth and
return a numeric score in [0.0, 1.0].

Scoring rules depend on `answer_format`:
- "mcq_single": 1.0 if the system answer selects the SAME option as the ground truth
  (allow paraphrase / extra explanation as long as the chosen option is unambiguous),
  else 0.0.
- "mcq_multi": the ground truth is a SET of options. 1.0 only if the system names exactly
  that set — no missing and no extra members. If it gets some but not all right (or adds
  wrong ones), give a fraction reflecting precision and recall (e.g. 2 of 3 correct with no
  extras ≈ 0.66). 0.0 if it shares no members with the ground truth.
- "numeric": 1.0 if the system's number equals the ground truth within `tolerance`
  (tolerance 0 means exact), else 0.0.
- "fuzzy_match": 1.0 if the system answer contains the ground-truth span or any of
  `accept_variants` (case-insensitive, ignoring surrounding punctuation), else 0.0.
- "free_form": follow `judge_rubric` if provided. Award 1.0 for a faithful, complete answer,
  0.5 for a partially correct answer, 0.0 for wrong / missing / hallucinated content. For
  audio_identity questions the rubric scores speaker identity AND content; if the speaker
  identity is wrong the score must not exceed 0.5.

Be robust to refusals, empty answers, and "I don't know" — those score 0.0.
Output STRICT JSON only, no prose, no code fences:
{"score": <float 0..1>, "verdict": "<correct|partial|incorrect>", "reason": "<one short sentence>"}"""


def build_judge_payload(item: Dict[str, Any], system_answer: str) -> Dict[str, Any]:
    payload: Dict[str, Any] = {
        "answer_format": item.get("answer_format"),
        "q_type": item.get("q_type"),
        "subtype": item.get("subtype"),
        "question": item.get("question"),
        "ground_truth": item.get("ground_truth"),
        "system_answer": system_answer,
    }
    for opt_key in ("choices", "judge_rubric", "accept_variants", "tolerance"):
        if opt_key in item and item[opt_key] is not None:
            payload[opt_key] = item[opt_key]
    return payload


def judge_answer(client: OpenAI, model: str, item: Dict[str, Any],
                 system_answer: str) -> Dict[str, Any]:
    payload = build_judge_payload(item, system_answer)
    resp = client.chat.completions.create(
        model=model,
        temperature=0.0,
        max_tokens=300,
        response_format={"type": "json_object"},
        messages=[
            {"role": "system", "content": _JUDGE_SYS},
            {"role": "user", "content": json.dumps(payload, ensure_ascii=False)},
        ],
    )
    raw = (resp.choices[0].message.content or "").strip()
    data = json.loads(raw)
    score = float(data.get("score", 0.0))
    score = max(0.0, min(1.0, score))
    return {
        "score": score,
        "verdict": data.get("verdict", ""),
        "reason": data.get("reason", ""),
    }


# ---------------------------------------------------------------------------
# Aggregation / reporting
# ---------------------------------------------------------------------------
def summarize(results: List[Dict[str, Any]]) -> Dict[str, Any]:
    """Build per-type, per-subtype and overall accuracy from scored results."""
    def acc_block(rows: List[Dict[str, Any]]) -> Dict[str, Any]:
        n = len(rows)
        if n == 0:
            return {"n": 0, "accuracy": 0.0, "strict_accuracy": 0.0}
        mean_score = sum(r["score"] for r in rows) / n
        strict = sum(1 for r in rows if r["score"] >= 0.999) / n
        return {"n": n, "accuracy": round(mean_score, 4),
                "strict_accuracy": round(strict, 4)}

    by_type: Dict[str, List] = defaultdict(list)
    by_subtype: Dict[str, List] = defaultdict(list)
    for r in results:
        by_type[r["q_type"]].append(r)
        by_subtype[f"{r['q_type']}.{r['subtype']}"].append(r)

    return {
        "overall": acc_block(results),
        "by_q_type": {k: acc_block(v) for k, v in sorted(by_type.items())},
        "by_subtype": {k: acc_block(v) for k, v in sorted(by_subtype.items())},
    }


def print_summary(summary: Dict[str, Any]) -> None:
    def line(label: str, block: Dict[str, Any]) -> None:
        print(f"  {label:<38} n={block['n']:>3}  "
              f"acc={block['accuracy']:.3f}  strict={block['strict_accuracy']:.3f}")

    print("\n================ RESULTS BY SUBTYPE ================")
    for k, b in summary["by_subtype"].items():
        line(k, b)
    print("\n================ RESULTS BY Q_TYPE ================")
    for k, b in summary["by_q_type"].items():
        line(k, b)
    print("\n================ OVERALL ================")
    line("ALL", summary["overall"])


# ---------------------------------------------------------------------------
# Driver
# ---------------------------------------------------------------------------
def main() -> int:
    p = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    p.add_argument("--benchmark", default="tests/new_bench_with_audio_v2.json",
                   help="Path to the benchmark JSON (default: %(default)s).")
    p.add_argument("--base-url", default="http://127.0.0.1:8006")
    p.add_argument("--audio-root", default=None,
                   help="Root holding the MELD dev clips on THIS machine (e.g. the "
                        "backend container's /app/MELD.Raw). audio_identity clips are "
                        "relocated here by basename, since the benchmark stores host "
                        "paths. Omit if the benchmark's audio_path values resolve as-is.")
    p.add_argument("--judge-model", default="gpt-4o",
                   help="OpenAI model used as the LLM judge (default: %(default)s).")
    p.add_argument("--output", default=None,
                   help="Output directory or .jsonl path for per-question results. "
                        "A matching *_summary.json is written alongside it.")
    p.add_argument("--max-new-tokens", type=int, default=400,
                   help="Token budget for the system answer (default: %(default)s).")
    p.add_argument("--max-prompt-chars", type=int, default=95000,
                   help="Truncate the recommended prompt to this many chars before "
                        "answering, to stay inside the answerer's context window.")
    p.add_argument("--only", nargs="*", default=None,
                   help="Restrict to q_types or 'q_type.subtype' ids.")
    p.add_argument("--limit", type=int, default=-1,
                   help="Max number of questions to evaluate; -1 = all.")
    p.add_argument("--resume", action="store_true",
                   help="If the output JSONL exists, skip ids already scored in it.")
    args = p.parse_args()

    if "OPENAI_API_KEY" not in os.environ:
        sys.exit("Set OPENAI_API_KEY in your environment (used for the LLM judge).")

    bench_path = Path(args.benchmark)
    if not bench_path.is_file():
        sys.exit(f"Benchmark file not found: {bench_path}")
    with bench_path.open(encoding="utf-8") as f:
        benchmark = json.load(f)

    # Resolve output paths.
    if args.output:
        out_arg = Path(args.output)
        if out_arg.suffix == ".jsonl":
            out_path = out_arg
        else:
            stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
            out_path = out_arg / f"meld_v2_eval_{stamp}.jsonl"
    else:
        stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        out_path = Path(__file__).resolve().parent / "meld_v2_results" / f"meld_v2_eval_{stamp}.jsonl"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    summary_path = out_path.with_name(out_path.stem + "_summary.json")

    def selected(item: Dict[str, Any]) -> bool:
        if not args.only:
            return True
        qt, st = item.get("q_type"), item.get("subtype")
        return qt in args.only or f"{qt}.{st}" in args.only

    items = [it for it in benchmark if selected(it)]
    if args.limit and args.limit > 0:
        items = items[: args.limit]

    try:
        assert_backend_local(args.base_url)
    except Exception as e:
        print(f"FATAL: {e}", file=sys.stderr)
        return 2

    done_ids: set = set()
    if args.resume and out_path.exists():
        with out_path.open() as f:
            for line in f:
                try:
                    done_ids.add(json.loads(line).get("id"))
                except Exception:
                    pass
        print(f"[resume] {len(done_ids)} ids already scored in {out_path}")

    client = OpenAI()

    print(f"Benchmark: {bench_path}  ({len(items)} questions to evaluate)")
    print(f"Backend:   {args.base_url}  (answerer: backend /llm/generate)")
    print(f"Judge:     {args.judge_model}")
    print(f"Writing per-question results to {out_path}\n", flush=True)

    results: List[Dict[str, Any]] = []
    n_ok = n_fail = 0
    t_start = time.perf_counter()

    with out_path.open("a") as out_f:
        for i, item in enumerate(items, start=1):
            qid = item.get("id", f"q_{i}")
            if qid in done_ids:
                continue

            qtype = item.get("q_type", "")
            subtype = item.get("subtype", "")
            question = item.get("question", "")
            audio_path = resolve_audio_path(item, args.audio_root) if qtype == "audio_identity" else None

            t_q = time.perf_counter()
            try:
                prompt = retrieve_prompt(args.base_url, question, audio_path)
                if len(prompt) > args.max_prompt_chars:
                    prompt = prompt[: args.max_prompt_chars] + "\n\n[...truncated...]"
                system_answer = llm_generate(args.base_url, prompt, args.max_new_tokens)
                verdict = judge_answer(client, args.judge_model, item, system_answer)
            except Exception as e:
                n_fail += 1
                print(f"[{i}/{len(items)}] {qid} FAIL "
                      f"({time.perf_counter() - t_q:.1f}s): {e}", flush=True)
                continue

            row = {
                "id": qid,
                "q_type": qtype,
                "subtype": subtype,
                "answer_format": item.get("answer_format"),
                "question": question,
                "ground_truth": item.get("ground_truth"),
                "system_answer": system_answer,
                "score": verdict["score"],
                "verdict": verdict["verdict"],
                "reason": verdict["reason"],
            }
            out_f.write(json.dumps(row, ensure_ascii=False) + "\n")
            out_f.flush()
            results.append(row)
            n_ok += 1

            running = sum(r["score"] for r in results) / max(len(results), 1)
            print(f"[{i}/{len(items)}] {qid:<34} "
                  f"score={verdict['score']:.2f} ({verdict['verdict']:<9}) "
                  f"running_acc={running:.3f}  {time.perf_counter() - t_q:.1f}s",
                  flush=True)

    # If resuming, fold previously-scored rows back in for the summary.
    if args.resume and done_ids:
        scored_now = {r["id"] for r in results}
        with out_path.open() as f:
            for line in f:
                try:
                    prev = json.loads(line)
                except Exception:
                    continue
                if prev.get("id") not in scored_now and "score" in prev:
                    results.append(prev)

    summary = summarize(results)
    summary["meta"] = {
        "benchmark": str(bench_path),
        "base_url": args.base_url,
        "judge_model": args.judge_model,
        "n_evaluated": len(results),
        "n_failed": n_fail,
        "timestamp": datetime.utcnow().isoformat(),
        "elapsed_sec": round(time.perf_counter() - t_start, 1),
    }
    with summary_path.open("w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2, ensure_ascii=False)

    print_summary(summary)
    print(f"\nDone. {n_ok} scored, {n_fail} failed.")
    print(f"Per-question results: {out_path}")
    print(f"Summary:              {summary_path}")
    return 0 if n_fail == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
